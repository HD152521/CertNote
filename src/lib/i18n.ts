export type Language = 'ko' | 'en';

/**
 * Normalize language from untrusted input (API requests, query params)
 * Defaults to 'ko' for unknown values
 */
export function normalizeLanguage(input: unknown): Language {
  return input === 'en' ? 'en' : 'ko';
}

/**
 * Detect language from pathname
 * /en/* → 'en', else 'ko'
 */
export function detectLanguage(pathname: string): Language {
  return pathname.startsWith('/en') ? 'en' : 'ko';
}

